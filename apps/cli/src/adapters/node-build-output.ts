import { randomUUID } from 'node:crypto';
import { lstat, mkdir, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';
import { PipelineError } from '@assets-pipeline/core';
import type { BuildArtifact } from '@assets-pipeline/core';

const buildMarker = '.assets-pipeline-build';

function isMissing(error: unknown): boolean {
  return typeof error === 'object' && error !== null && 'code' in error && error.code === 'ENOENT';
}

async function checkedOutput(root: string, requested: string): Promise<string> {
  const output = isAbsolute(requested) ? resolve(requested) : resolve(root, requested);
  const rel = relative(root, output);
  if (rel === '' || rel === '..' || rel.startsWith(`..${sep}`) || isAbsolute(rel)) {
    throw new PipelineError('INVALID_INPUT', 'La salida debe ser una subcarpeta del repositorio.');
  }
  if (rel.split(sep).some((segment) => segment.toLowerCase() === '.assets-pipeline-cache')) {
    throw new PipelineError(
      'INVALID_INPUT',
      'La salida no puede estar dentro de la carpeta interna.',
    );
  }
  let current = root;
  for (const segment of rel.split(sep)) {
    current = join(current, segment);
    try {
      if ((await lstat(current)).isSymbolicLink()) {
        throw new PipelineError(
          'INVALID_INPUT',
          'La salida no puede atravesar enlaces simbólicos.',
        );
      }
    } catch (error) {
      if (!isMissing(error)) throw error;
    }
  }
  return output;
}

/**
 * Publishes the artifacts of a build into a marked repository subfolder.
 * Refuses to replace a folder that was not generated by Assets Pipeline and
 * swaps the new output in atomically.
 */
export async function publishBuildOutput(
  root: string,
  requested: string,
  artifacts: readonly BuildArtifact[],
): Promise<{ output: string; files: readonly string[] }> {
  const output = await checkedOutput(root, requested);
  const parent = resolve(output, '..');
  await mkdir(parent, { recursive: true });
  try {
    const existing = await readdir(output);
    if (existing.length > 0 && !existing.includes(buildMarker)) {
      throw new PipelineError(
        'ALREADY_EXISTS',
        `La salida existe y no pertenece a Assets Pipeline: ${output}`,
      );
    }
  } catch (error) {
    if (!isMissing(error)) throw error;
  }
  const temporary = join(parent, `.assets-pipeline-build-${randomUUID()}`);
  const backup = join(parent, `.assets-pipeline-backup-${randomUUID()}`);
  await mkdir(temporary);
  try {
    for (const artifact of artifacts) {
      await writeFile(join(temporary, artifact.fileName), artifact.contents);
    }
    await writeFile(join(temporary, buildMarker), 'generated\n');
    let hadOutput = false;
    try {
      await rename(output, backup);
      hadOutput = true;
    } catch (error) {
      if (!isMissing(error)) throw error;
    }
    try {
      await rename(temporary, output);
    } catch (error) {
      if (hadOutput) await rename(backup, output);
      throw error;
    }
    if (hadOutput) await rm(backup, { recursive: true, force: true });
    return { output, files: artifacts.map((artifact) => artifact.fileName) };
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}
